#!/usr/bin/env node
/**
 * Regenerate src/jurisdictions.ts from the JSON files in rules/. Run after
 * adding a jurisdiction: npm run gen -w @shiftowed/rules
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = readdirSync(join(root, "rules"))
  .filter((f) => f.endsWith(".json"))
  .sort();
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const ident = (f) =>
  f
    .replace(/\.json$/, "")
    .split("-")
    .map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join("");

const out = `// Generated by scripts/gen-registry.mjs. Do not edit by hand.
import type { Jurisdiction } from "./types.js";
${files.map((f) => `import ${ident(f)} from "../rules/${f}" with { type: "json" };`).join("\n")}

/** Version of the rules data (matches the package version). */
export const RULES_VERSION = ${JSON.stringify(pkg.version)};

/** Every jurisdiction, sorted by id. */
export const JURISDICTIONS: readonly Jurisdiction[] = [
${files.map((f) => `  ${ident(f)} as Jurisdiction,`).join("\n")}
];

/** Look up a jurisdiction by id, e.g. "us-wa-seattle". */
export function getJurisdiction(id: string): Jurisdiction | undefined {
  return JURISDICTIONS.find((j) => j.id === id);
}
`;
writeFileSync(join(root, "src", "jurisdictions.ts"), out);
console.log(`src/jurisdictions.ts: ${files.length} jurisdictions`);
